function makeAddress(spokenName: string): string {
  const clean = String(spokenName || '').replace(/\s+/g, ' ').trim() || 'Phật tử';
  return /^phật\s+tử(?:\s|$)/iu.test(clean) ? clean : `Phật tử ${clean}`;
}
function hashForRotation(key: string): number {
  let hash = 2166136261;
  for (let i = 0; i < key.length; i++) {
    hash ^= key.charCodeAt(i);
    hash = Math.imul(hash, 16777619);
  }
  return hash >>> 0;
}
export function pickTempleWelcomeDialogue(spokenName: string, userId: string): string {
  const index = hashForRotation(userId) % TEMPLE_WELCOME_DIALOGUES.length;
  return TEMPLE_WELCOME_DIALOGUES[index].replace(/\{name\}/g, makeAddress(spokenName));
}
export function pickTempleLikeDialogue(spokenName: string, likes: number, userId: string): string {
  const ordinal = Math.max(0, Math.floor(Math.max(0, likes) / 1000) - 1);
  const index = (hashForRotation(userId) + ordinal) % TEMPLE_LIKE_DIALOGUES.length;
  return TEMPLE_LIKE_DIALOGUES[index].replace(/\{name\}/g, makeAddress(spokenName));
}
